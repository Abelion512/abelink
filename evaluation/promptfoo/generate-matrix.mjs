// Generator matrix Promptfoo dari fixture AbelinkBench PR46.
// Prinsip: SATU sumber kebenaran untuk task (PR46_TASKS) — generator hanya
// menerjemahkan fixture -> format Promptfoo (YAML + JSONL tests). Verdict tetap
// dari oracle world-state fixture (tidak pernah dari teks jawaban model).
//
// Pakai (dari root repo):
//   bun evaluation/promptfoo/generate-matrix.mjs
// Hasil (di evaluation/promptfoo/generated/):
//   promptfooconfig.yaml, pr46-tests.jsonl, manifest.json, README.md
//
// Menjalankan eval penuh butuh promptfoo terpasang + provider model hidup:
//   promptfoo eval -c evaluation/promptfoo/generated/promptfooconfig.yaml
// Subset offline (tanpa LLM) tetap tersedia lewat jalur AbelinkBench:
//   bun evaluation/run.mjs --suite pr46

import { mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import matrix from '../pr46-matrix.mjs'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const OUT_DIR = path.join(HERE, 'generated')

const {
  PR46_TASKS,
  PR46_LANE_COUNTS,
  PR46_TOTAL_FIXTURES,
  PR46_MINIMAL_OFFLINE,
  PR46_ABLATION_PAIRS,
} = matrix

function buildConfigYaml() {
  return [
    '# AUTO-GENERATED by evaluation/promptfoo/generate-matrix.mjs — jangan edit manual.',
    '# Sumber kebenaran: evaluation/pr46-matrix.mjs (fixture AbelinkBench PR46).',
    '# Verdict = oracle world-state fixture (verify()), BUKAN teks jawaban model.',
    '# Butuh promptfoo terpasang + kredensial provider yang dipakai CLI.',
    "description: 'AbelinkBench PR46 via adapter Abelink'",
    'prompts:',
    "  - '{{task}}'",
    'providers:',
    '  - file://evaluation/promptfoo/abelink-provider.mjs',
    '    config:',
    "      workspace: '{{workspace}}'",
    "      effort: '{{effort}}'",
    '      timeoutMs: 900000',
    'tests: file://evaluation/promptfoo/generated/pr46-tests.jsonl',
    '',
  ].join('\n')
}

// Prompt fixture: PR46 menyimpan teks task pada field `prompt` (fallback
// `task`/`instruction` untuk ketahanan bila field berubah di masa depan).
const taskText = (t) => String(t.prompt ?? t.task ?? t.instruction ?? '')

function buildJsonl(tasks) {
  const lines = tasks.map((t) =>
    JSON.stringify({
      description: `${t.taskId} [${t.lane}${t.variant ? '/' + t.variant : ''}]`,
      vars: {
        task: taskText(t),
        workspace: '__WORKSPACE__',
        effort: t.effort ?? 'medium',
      },
      assert: [
        {
          type: 'javascript',
          metric: 'deterministic',
          // Verdict dari sinyal engine (oracle world-state fixture),
          // bukan dari teks jawaban model (anti-fabrikasi).
          value: 'metadata.engineSuccess === true && metadata.outcome !== "needs_user"',
        },
      ],
    })
  )
  return lines.join('\n') + '\n'
}

function main() {
  const args = process.argv.slice(2)
  const get = (flag) => {
    const i = args.indexOf(flag)
    return i >= 0 ? args[i + 1] : null
  }
  const outDirArg = get('--out')
  const outDir = outDirArg ? path.resolve(outDirArg) : OUT_DIR
  const tasks = Object.values(PR46_TASKS)

  mkdirSync(outDir, { recursive: true })
  writeFileSync(path.join(outDir, 'promptfooconfig.yaml'), buildConfigYaml())
  writeFileSync(path.join(outDir, 'pr46-tests.jsonl'), buildJsonl(tasks))
  writeFileSync(
    path.join(outDir, 'manifest.json'),
    JSON.stringify(
      {
        generator: 'evaluation/promptfoo/generate-matrix.mjs',
        generatedAt: new Date().toISOString(),
        suite: 'pr46',
        totalFixtures: tasks.length,
        expectedTotal: PR46_TOTAL_FIXTURES,
        laneCounts: PR46_LANE_COUNTS,
        minimalOffline: PR46_MINIMAL_OFFLINE,
        ablationPairs: PR46_ABLATION_PAIRS,
      },
      null,
      2
    ) + '\n'
  )
  const readme = [
    '# Matrix Promptfoo PR46 (auto-generated)',
    '',
    `Total fixture: ${tasks.length} (harus = ${PR46_TOTAL_FIXTURES}); lane counts: ${JSON.stringify(PR46_LANE_COUNTS)}`,
    '',
    'Verdict dari oracle world-state fixture (pr46-matrix.mjs verify()).',
    'Teks jawaban model BUKAN sinyal sukses (anti-fabrikasi).',
    '',
    'Menjalankan:',
    '  promptfoo eval -c evaluation/promptfoo/generated/promptfooconfig.yaml',
    '',
    'Subset offline tanpa LLM tetap via AbelinkBench:',
    '  bun evaluation/run.mjs --suite pr46',
    '',
    `Ablation pair: ${JSON.stringify(PR46_ABLATION_PAIRS)}`,
    `Minimal offline: ${PR46_MINIMAL_OFFLINE.join(', ')}`,
    '',
  ].join('\n')
  writeFileSync(path.join(outDir, 'README.md'), readme)

  console.log(`[generate-matrix] OK: ${tasks.length} fixture -> ${outDir}`)
  if (tasks.length !== PR46_TOTAL_FIXTURES) {
    console.error(`[generate-matrix] MISMATCH: ${tasks.length} != ${PR46_TOTAL_FIXTURES}`)
    process.exit(2)
  }
}

main()
