// Locale dicts for the /#/config surface (Phase A: EN default, ZH second).
// No dependency. Wired to the existing `config.language` value.
// Legacy 'id' values fall back to EN.
export const LOCALES = ['en', 'zh']

export function getLocale(langOrConfig) {
  const raw =
    typeof langOrConfig === 'string' ? langOrConfig : langOrConfig?.language
  const v = String(raw || 'en').toLowerCase()
  if (v.startsWith('zh')) return 'zh'
  if (v === 'en' || v === 'en-us' || v === 'en_us') return 'en'
  return 'en'
}

// BCP-47 tag for toLocaleTimeString / Intl — never hardcode 'id-ID'.
export function localeTag(langOrConfig) {
  return getLocale(langOrConfig) === 'zh' ? 'zh-CN' : 'en-US'
}

